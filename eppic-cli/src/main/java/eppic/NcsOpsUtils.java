package eppic;

import java.util.ArrayList;
import java.util.List;

import javax.vecmath.Matrix4d;

import org.biojava.nbio.structure.PDBCrystallographicInfo;
import org.biojava.nbio.structure.Structure;
import org.biojava.nbio.structure.xtal.CrystalCell;
import org.biojava.nbio.structure.xtal.SpaceGroup;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Utilities to deal with non-crystallographic symmetry (NCS) operators.
 *
 * @author Jose Duarte
 */
public class NcsOpsUtils {

	private static final Logger logger = LoggerFactory.getLogger(NcsOpsUtils.class);

	/**
	 * Tolerance to consider 2 operators (in crystal coordinates) equal
	 */
	private static final double TOLERANCE = 0.001;

	/**
	 * Removes from the given structure the NCS operators that are redundant with the
	 * crystallographic symmetry: those for which the copy that they generate is the same (through
	 * an operator of the space group and a lattice translation) as the deposited coordinates or
	 * as the copy generated by a previous NCS operator.
	 * <p>
	 * That happens for instance in viral capsids sitting on a crystallographic axis for which
	 * the full set of 60 icosahedral operators was deposited (e.g. 3zxa in I 2 2 2), or when
	 * a crystallographic operator is also given as NCS operator (e.g. 4pb6).
	 * Expanding redundant operators results in chains that occupy the same place in the crystal.
	 * <p>
	 * If no operators are left the NCS operators of the structure are set to null.
	 * @param structure
	 * @return the number of NCS operators removed
	 */
	public static int removeCrystallographicNcsOps(Structure structure) {

		PDBCrystallographicInfo xtalInfo = structure.getCrystallographicInfo();
		if (xtalInfo == null) return 0;

		Matrix4d[] ncsOps = xtalInfo.getNcsOperators();
		if (ncsOps == null || ncsOps.length == 0) return 0;

		CrystalCell cell = xtalInfo.getCrystalCell();
		SpaceGroup sg = xtalInfo.getSpaceGroup();
		if (cell == null || sg == null) return 0;

		// the operators (in crystal coordinates) that we keep, the first one being the identity (the deposited coordinates)
		List<Matrix4d> keptXtal = new ArrayList<>();
		Matrix4d identity = new Matrix4d();
		identity.setIdentity();
		keptXtal.add(identity);

		List<Matrix4d> kept = new ArrayList<>();

		for (Matrix4d ncsOp : ncsOps) {
			Matrix4d ncsOpXtal = cell.transfToCrystal(ncsOp);

			boolean redundant = false;
			for (Matrix4d keptOp : keptXtal) {
				// if ncsOp = S * keptOp with S an operator of the space group, then both generate the same crystal
				Matrix4d s = new Matrix4d(keptOp);
				s.invert();
				s.mul(ncsOpXtal, s);
				if (isCrystallographic(s, sg)) {
					redundant = true;
					break;
				}
			}

			if (!redundant) {
				keptXtal.add(ncsOpXtal);
				kept.add(ncsOp);
			}
		}

		int numRemoved = ncsOps.length - kept.size();

		if (numRemoved > 0) {
			logger.warn("{} out of {} NCS operators are redundant with the crystallographic symmetry of space group {}. They will be ignored",
					numRemoved, ncsOps.length, sg.getShortSymbol());
			xtalInfo.setNcsOperators(kept.isEmpty() ? null : kept.toArray(new Matrix4d[0]));
		}

		return numRemoved;
	}

	/**
	 * Returns true if the given operator (in crystal coordinates) is an operator of the given
	 * space group, modulo lattice translations.
	 * @param m
	 * @param sg
	 * @return
	 */
	private static boolean isCrystallographic(Matrix4d m, SpaceGroup sg) {
		for (int i = 0; i < sg.getNumOperators(); i++) {
			if (equalsModuloLattice(m, sg.getTransformation(i))) {
				return true;
			}
		}
		return false;
	}

	private static boolean equalsModuloLattice(Matrix4d m1, Matrix4d m2) {
		for (int i = 0; i < 3; i++) {
			for (int j = 0; j < 3; j++) {
				if (Math.abs(m1.getElement(i, j) - m2.getElement(i, j)) > TOLERANCE) {
					return false;
				}
			}
			double diff = m1.getElement(i, 3) - m2.getElement(i, 3);
			if (Math.abs(diff - Math.round(diff)) > TOLERANCE) {
				return false;
			}
		}
		return true;
	}
}
